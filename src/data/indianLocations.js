export const getStatesList = () => Object.keys(INDIAN_LOCATIONS);

export const getDistrictsList = (stateName) => {
  if (!stateName || !INDIAN_LOCATIONS[stateName]) {
    return Object.keys(INDIAN_LOCATIONS['Punjab'].districts);
  }
  return Object.keys(INDIAN_LOCATIONS[stateName].districts);
};

export const getTehsilsList = (stateName, districtName) => {
  if (!stateName || !districtName || !INDIAN_LOCATIONS[stateName] || !INDIAN_LOCATIONS[stateName].districts[districtName]) {
    return ['Central Region', 'North Tehsil', 'South Tehsil', 'East Block'];
  }
  return INDIAN_LOCATIONS[stateName].districts[districtName];
};
